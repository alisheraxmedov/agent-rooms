RECORD_NAME = "installed.json"
TRUST_FALLBACK = (
    "  The profile was written without trust: run `/hooks` once inside `codex-rooms` and trust the Stop hook."
)


def install_targets(home: Path) -> dict[str, Path]:
    cfg = config_dir(home)
    return {
        "claude_mcp": cfg / "claude" / "mcp.json",
        "claude_settings": cfg / "claude" / "settings.json",
        "codex_profile": home / ".codex" / "rooms.config.toml",
        "claude_wrapper": home / ".local" / "bin" / "claude-rooms",
        "codex_wrapper": home / ".local" / "bin" / "codex-rooms",
    }


def read_token(home: Path, agent: str, fs: Fs) -> str:
    path = token_path(home, agent)
    token = path.read_text(encoding="utf-8").strip() if path.is_file() else ""
    if token:
        return token
    if fs.dry_run:
        print(f"  note: {path} is missing, run tokens first (the dry run uses a placeholder)")
        return "<TOKEN>"
    raise SetupError(f"token file {path} is missing: run tokens first")


def load_record(home: Path) -> set[str]:
    try:
        files = json.loads((config_dir(home) / RECORD_NAME).read_text(encoding="utf-8"))["files"]
    except (OSError, ValueError, KeyError, TypeError):
        return set()
    return {f for f in files if isinstance(f, str)} if isinstance(files, list) else set()


def existing_trusted_hash(existing: str | None, hook_block: str, profile_path: Path) -> str | None:
    if not existing or hook_block not in existing:
        return None
    state = f"[hooks.state.{json.dumps(f'{profile_path}:stop:0:0')}]"
    match = re.search(r'trusted_hash = "(sha256:[0-9a-f]+)"', existing)
    return match.group(1) if match and state in existing else None


def codex_trusted_hash(hook_block: str, existing: str | None, profile_path: Path, fs: Fs) -> str | None:
    reused = existing_trusted_hash(existing, hook_block, profile_path)
    if reused or fs.dry_run:
        if not reused:
            print("  note: Codex hook trust is seeded and verified during the real install")
        return reused
    try:
        digest = seed_codex_trust(hook_block)
    except CodexTrustError as error:
        print(f"warning: could not pre-seed Codex hook trust ({error}).\n{TRUST_FALLBACK}")
        return None
    print("  codex hook trust: seeded and verified (trusted)")
    return digest


def cmd_install(args: argparse.Namespace, fs: Fs) -> int:
    home, rooms_repo, url = args.home, args.rooms_repo, args.url
    targets = install_targets(home)
    profile_path = targets["codex_profile"]
    claude_token = read_token(home, "claude", fs)
    codex_token = read_token(home, "codex", fs)
    codex_token_file = token_path(home, "codex")
    existing = profile_path.read_text(encoding="utf-8") if profile_path.is_file() else None
    hook_block = render_codex_hook_block(rooms_repo, codex_token_file, url)
    trusted = codex_trusted_hash(hook_block, existing, profile_path, fs)
    files = [
        (targets["claude_mcp"], to_json(render_claude_mcp(url, claude_token)), 0o600),
        (
            targets["claude_settings"],
            to_json(render_claude_settings(rooms_repo, token_path(home, "claude"), url)),
            0o600,
        ),
        (
            profile_path,
            render_codex_profile(
                url, codex_token, rooms_repo, codex_token_file, profile_path, trusted_hash=trusted
            ),
            0o600,
        ),
        (targets["claude_wrapper"], render_wrapper("claude-rooms"), 0o755),
        (targets["codex_wrapper"], render_wrapper("codex-rooms"), 0o755),
    ]
    recorded = load_record(home)
    for path, text, _mode in files:
        if path.is_file() and str(path) not in recorded and path.read_text(encoding="utf-8") != text:
            raise SetupError(f"{path} already exists and was not created by rooms_setup; move it away first")
    fs.mkdir(config_dir(home), 0o700)
    fs.mkdir(config_dir(home) / "claude", 0o700)
    record = to_json({"version": 1, "files": sorted(str(path) for path, _text, _mode in files)})
    statuses = [fs.write(config_dir(home) / RECORD_NAME, record, 0o600)]
    statuses += [fs.write(path, text, mode) for path, text, mode in files]
    if all(status == "unchanged" for status in statuses):
        print("Nothing to change: already installed.")
    elif fs.dry_run:
        print("Dry run: nothing was written.")
    else:
        print("Installed. Start sessions with `claude-rooms` / `codex-rooms` (~/.local/bin must be on PATH).")
    return 0


def cmd_uninstall(args: argparse.Namespace, fs: Fs) -> int:
    home = args.home
    record = config_dir(home) / RECORD_NAME
    if not record.is_file():
        print("Nothing to uninstall: no installed.json record.")
    else:
        recorded = load_record(home)
        for path in install_targets(home).values():
            if str(path) in recorded:
                fs.remove(path)
        fs.remove(record)
        fs.rmdir_if_empty(config_dir(home) / "claude")
    if args.purge_tokens:
        for agent in AGENTS:
            fs.remove(token_path(home, agent))
        fs.rmdir_if_empty(config_dir(home))
    print("Tokens were left in place." if not args.purge_tokens else "Token files removed.")
    return 0


def opencode_token_ref(home: Path) -> str:
    if home == Path.home():
        return "~/.config/agent-rooms/opencode.token"
    return str(token_path(home, "opencode"))


def child(parent: dict[str, Any], key: str, kind: type) -> Any:
    value = parent.setdefault(key, kind())
    if not isinstance(value, kind):
        raise SetupError(f"existing '{key}' has an unexpected type ({type(value).__name__}); fix it by hand")
    return value


def prune(parent: dict[str, Any], key: str) -> None:
    if key in parent and not parent[key]:
        del parent[key]


def plugin_package(plugin: Any) -> Any:
    return plugin.get("package") if isinstance(plugin, dict) else plugin


def merge_opencode(existing: dict[str, Any], ours: dict[str, Any]) -> dict[str, Any]:
    out = copy.deepcopy(existing)
    out.setdefault("$schema", ours["$schema"])
    plugins, entry = child(out, "plugins", list), ours["plugins"][0]
    slots = [i for i, plugin in enumerate(plugins) if plugin_package(plugin) == entry["package"]]
    if slots:
        plugins[slots[0]] = entry
    else:
        plugins.append(entry)
    child(child(out, "mcp", dict), "servers", dict)["rooms"] = ours["mcp"]["servers"]["rooms"]
    permissions = child(out, "permissions", list)
    if ours["permissions"][0] not in permissions:
        permissions.append(ours["permissions"][0])
    child(out, "agents", dict)["rooms-reviewer"] = ours["agents"]["rooms-reviewer"]
    child(out, "experimental", dict).setdefault(
        "location_idle_timeout", ours["experimental"]["location_idle_timeout"]
    )
    return out


def unmerge_opencode(existing: dict[str, Any], ours: dict[str, Any]) -> dict[str, Any]:
    out = copy.deepcopy(existing)
    package = ours["plugins"][0]["package"]
    if isinstance(out.get("plugins"), list):
        out["plugins"] = [p for p in out["plugins"] if plugin_package(p) != package]
        prune(out, "plugins")
    servers = out.get("mcp", {}).get("servers") if isinstance(out.get("mcp"), dict) else None
    if isinstance(servers, dict):
        servers.pop("rooms", None)
        prune(out["mcp"], "servers")
        prune(out, "mcp")
    if isinstance(out.get("permissions"), list):
        out["permissions"] = [r for r in out["permissions"] if r != ours["permissions"][0]]
        prune(out, "permissions")
    if isinstance(out.get("agents"), dict):
        out["agents"].pop("rooms-reviewer", None)
        prune(out, "agents")
    experimental = out.get("experimental")
    if isinstance(experimental, dict):
        if experimental.get("location_idle_timeout") == ours["experimental"]["location_idle_timeout"]:
            del experimental["location_idle_timeout"]
        prune(out, "experimental")
    return out


def merge_agy_mcp(existing: dict[str, Any], ours: dict[str, Any]) -> dict[str, Any]:
    out = copy.deepcopy(existing)
    child(out, "mcpServers", dict)["rooms"] = ours["mcpServers"]["rooms"]
    return out


def unmerge_agy_mcp(existing: dict[str, Any]) -> dict[str, Any]:
    out = copy.deepcopy(existing)
    if isinstance(out.get("mcpServers"), dict):
        out["mcpServers"].pop("rooms", None)
        prune(out, "mcpServers")
    return out


def merge_agy_hooks(existing: dict[str, Any], ours: dict[str, Any]) -> dict[str, Any]:
    out = copy.deepcopy(existing)
    out["agent-rooms"] = ours["agent-rooms"]
    return out


def unmerge_agy_hooks(existing: dict[str, Any]) -> dict[str, Any]:
    out = copy.deepcopy(existing)
    out.pop("agent-rooms", None)
    return out


EXCLUDE_MARKER = "# agent-rooms (rooms_setup.py)"
EXCLUDE_PATTERNS = (".opencode/", ".agents/")


def git_output(repo: Path, *args: str) -> str | None:
    try:
        result = subprocess.run(  # noqa: S603
            ["git", "-C", str(repo), *args],  # noqa: S607
            capture_output=True,
            text=True,
            check=False,
            timeout=30,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    return result.stdout if result.returncode == 0 else None


def git_exclude_path(repo: Path) -> Path | None:
    if not (repo / ".git").exists():
        return None
    out = git_output(repo, "rev-parse", "--git-path", "info/exclude")
    if out is None:
        return repo / ".git" / "info" / "exclude" if (repo / ".git").is_dir() else None
    return repo / out.strip()


def add_excludes(repo: Path, fs: Fs) -> str:
    path = git_exclude_path(repo)
    if path is None:
        return "unchanged"
    text = path.read_text(encoding="utf-8") if path.is_file() else ""
    lines = text.splitlines()
    missing = [pattern for pattern in EXCLUDE_PATTERNS if pattern not in (line.strip() for line in lines)]
    if not missing:
        return fs.write(path, text)
    if EXCLUDE_MARKER in lines:
        at = lines.index(EXCLUDE_MARKER) + 1
        lines[at:at] = missing
        return fs.write(path, "\n".join(lines) + "\n")
    separator = "" if not text or text.endswith("\n") else "\n"
    return fs.write(path, text + separator + "\n".join([EXCLUDE_MARKER, *missing]) + "\n")


def remove_excludes(repo: Path, fs: Fs) -> str:
    path = git_exclude_path(repo)
    if path is None or not path.is_file():
        return "unchanged"
    text = path.read_text(encoding="utf-8")
    lines = text.splitlines()
    if EXCLUDE_MARKER not in lines:
        return "unchanged"
    start = lines.index(EXCLUDE_MARKER)
    end = start + 1
    while end < len(lines) and lines[end].strip() in EXCLUDE_PATTERNS:
        end += 1
    del lines[start:end]
    return fs.write(path, "".join(line + "\n" for line in lines))


def warn_if_tracked(repo: Path, relative_paths: list[str]) -> None:
    tracked = (git_output(repo, "ls-files", "--", *relative_paths) or "").split()
    if tracked:
        print(
            f"warning: tracked by git: {', '.join(tracked)}. "
            "Ignoring them does not help; .agents/mcp_config.json holds a token, do not commit it."
        )


def read_json_object(path: Path) -> dict[str, Any] | None:
    """Existing JSON object ({} when the file is missing); None when it is not plain JSON."""
    if not path.is_file():
        return {}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except ValueError:
        return None
    return data if isinstance(data, dict) else None


def refuse_edit(path: Path, snippet: str | None) -> str:
    print(
        f"error: {path} contains comments or is not a plain JSON object; not editing it.",
        file=sys.stderr,
    )
    if snippet is None:
        print("  Remove the Agent Rooms entries by hand (server 'rooms', plugin, rules).", file=sys.stderr)
    else:
        print(f"  Add this to it manually:\n{snippet}", file=sys.stderr)
    return "refused"


def apply_json(
    fs: Fs,
    path: Path,
    transform: Callable[[dict[str, Any]], dict[str, Any]],
    snippet: str | None,
    mode: int | None,
    *,
    delete_when_empty: bool = False,
) -> str:
    existing = read_json_object(path)
    if existing is None:
        return refuse_edit(path, snippet)
    result = transform(existing)
    if result == existing:
        return fs.write(path, path.read_text(encoding="utf-8"), mode) if path.is_file() else "unchanged"
    if delete_when_empty and not any(key != "$schema" for key in result):
        fs.remove(path)
        fs.rmdir_if_empty(path.parent)
        return "removed"
    return fs.write(path, to_json(result), mode)


def repo_argument(args: argparse.Namespace) -> Path:
    repo = args.path.expanduser().absolute()
    if not repo.is_dir():
        raise SetupError(f"{repo} is not a directory")
    return repo


def cmd_enable_repo(args: argparse.Namespace, fs: Fs) -> int:
    home, rooms_repo, url, repo = args.home, args.rooms_repo, args.url, repo_argument(args)
    read_token(home, "opencode", fs)
    agy_token = read_token(home, "agy", fs)
    opencode = render_opencode_project(url, rooms_repo, opencode_token_ref(home))
    agy_mcp_snippet = render_agy_mcp(url, f"<contents of {token_path(home, 'agy')}>")
    agy_hooks = render_agy_hooks(rooms_repo, token_path(home, "agy"), url)
    statuses = [
        apply_json(
            fs,
            repo / ".opencode" / "opencode.jsonc",
            lambda existing: merge_opencode(existing, opencode),
            to_json(opencode),
            None,
        ),
        apply_json(
            fs,
            repo / ".agents" / "mcp_config.json",
            lambda existing: merge_agy_mcp(existing, render_agy_mcp(url, agy_token)),
            to_json(agy_mcp_snippet),
            0o600,
        ),
        apply_json(
            fs,
            repo / ".agents" / "hooks.json",
            lambda existing: merge_agy_hooks(existing, agy_hooks),
            to_json(agy_hooks),
            None,
        ),
        add_excludes(repo, fs),
    ]
    warn_if_tracked(repo, [".opencode/opencode.jsonc", ".agents/mcp_config.json", ".agents/hooks.json"])
    if "refused" in statuses:
        return 1
    if all(status == "unchanged" for status in statuses):
        print("Nothing to change: repo already enabled.")
    elif fs.dry_run:
        print("Dry run: nothing was written.")
    else:
        print(f"Enabled {repo}. Start `opencode` / `agy` from that directory.")
    return 0


def cmd_disable_repo(args: argparse.Namespace, fs: Fs) -> int:
    rooms_repo, url, repo = args.rooms_repo, args.url, repo_argument(args)
    opencode = render_opencode_project(url, rooms_repo, opencode_token_ref(args.home))
    statuses = [
        apply_json(
            fs,
            repo / ".opencode" / "opencode.jsonc",
            lambda existing: unmerge_opencode(existing, opencode),
            None,
            None,
            delete_when_empty=True,
        ),
        apply_json(
            fs, repo / ".agents" / "mcp_config.json", unmerge_agy_mcp, None, 0o600, delete_when_empty=True
        ),
        apply_json(
            fs, repo / ".agents" / "hooks.json", unmerge_agy_hooks, None, None, delete_when_empty=True
        ),
        remove_excludes(repo, fs),
    ]
    if "refused" in statuses:
        return 1
    if all(status == "unchanged" for status in statuses):
        print("Nothing to disable: no Agent Rooms entries found.")
    elif fs.dry_run:
        print("Dry run: nothing was changed.")
    else:
        print(f"Disabled {repo}.")
    return 0


def row(state: str, label: str, path: Path) -> None:
    print(f"  {state:<8} {label:<22} {path}")


def has_entry(data: dict[str, Any] | None, *keys: str) -> bool | None:
    if data is None:
        return None
    for key in keys:
        if not isinstance(data, dict) or key not in data:
            return False
        data = data[key]
    return True


def json_row(label: str, path: Path, *keys: str) -> None:
    found = has_entry(read_json_object(path), *keys) if path.is_file() else False
    row("unknown" if found is None else "present" if found else "missing", label, path)


def cmd_status(args: argparse.Namespace, _fs: Fs) -> int:
    home = args.home
    repo = (args.path or Path.cwd()).expanduser().absolute()
    agents_file = args.rooms_repo / "config" / "agents.json"
    print("Server registry and tokens (values are never printed):")
    row("present" if agents_file.is_file() else "missing", "agents.json", agents_file)
    for agent in AGENTS:
        path = token_path(home, agent)
        row("present" if path.is_file() else "missing", f"{agent}.token", path)
    print("Installed profiles:")
    for name, path in install_targets(home).items():
        row("present" if path.is_file() else "missing", name, path)
    profile = install_targets(home)["codex_profile"]
    if profile.is_file():
        seeded = "trusted_hash" in profile.read_text(encoding="utf-8")
        print("  Codex hook trust: " + ("seeded" if seeded else "NOT seeded (run `/hooks` in codex-rooms)"))
    print(f"Repo {repo}:")
    json_row("opencode rooms server", repo / ".opencode" / "opencode.jsonc", "mcp", "servers", "rooms")
    json_row("agy rooms MCP server", repo / ".agents" / "mcp_config.json", "mcpServers", "rooms")
    json_row("agy agent-rooms hooks", repo / ".agents" / "hooks.json", "agent-rooms")
    exclude = git_exclude_path(repo)
    if exclude is not None:
        marked = exclude.is_file() and EXCLUDE_MARKER in exclude.read_text(encoding="utf-8")
        row("present" if marked else "missing", "git exclude entries", exclude)
    return 0


def cmd_tokens(args: argparse.Namespace, fs: Fs) -> int:
    human, bad = ensure_tokens(args.home, args.rooms_repo, fs, args.rotate)
    for name in bad:
        print(
            f"error: {token_path(args.home, name)} is missing or does not match its hash in agents.json: "
            f"run `tokens --rotate {name}`",
            file=sys.stderr,
        )
    if human and fs.dry_run:
        print("  would print the human token once (nothing secret is printed in a dry run)")
    elif human:
        print_human_token(human)
    print(f"Agent token files are in {config_dir(args.home)}; agent tokens are never printed.")
    if args.rotate:
        print(f"Rotated {args.rotate}: {ROTATE_HINTS[args.rotate]}.")
        print(
            "Restart the server so it reloads config/agents.json (e.g. `docker compose restart agent-rooms`)."
        )
    return 1 if bad else 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="rooms_setup.py", description="Isolated Agent Rooms client setup.")
    parser.add_argument("--home", type=Path, default=Path.home(), help=argparse.SUPPRESS)
    parser.add_argument("--rooms-repo", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--url", default=DEFAULT_URL)
    parser.add_argument("--dry-run", action="store_true", help="print planned changes, change nothing")
    commands = parser.add_subparsers(dest="command", required=True)
    tokens = commands.add_parser("tokens", help="create or hash agent tokens and write the token files")
    tokens.add_argument("--rotate", choices=AGENTS, help="generate a new token for one agent")
    tokens.set_defaults(run=cmd_tokens)
    commands.add_parser("install", help="write the Claude and Codex profiles and wrappers").set_defaults(
        run=cmd_install
    )
    uninstall = commands.add_parser("uninstall", help="remove exactly what install created")
    uninstall.add_argument("--purge-tokens", action="store_true", help="also delete the token files")
    uninstall.set_defaults(run=cmd_uninstall)
    status = commands.add_parser("status", help="show what is installed and enabled")
    status.add_argument("path", type=Path, nargs="?", help="repo to inspect (default: current directory)")
    status.set_defaults(run=cmd_status)
    for name, run, text in (
        ("enable-repo", cmd_enable_repo, "enable OpenCode and agy for one repo"),
        ("disable-repo", cmd_disable_repo, "remove the entries enable-repo added"),
    ):
        repo_cmd = commands.add_parser(name, help=text)
        repo_cmd.add_argument("path", type=Path)
        repo_cmd.set_defaults(run=run)
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    args.home = args.home.expanduser().absolute()
    args.rooms_repo = args.rooms_repo.expanduser().absolute()
    try:
        return args.run(args, Fs(args.home, args.dry_run))
    except SetupError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
