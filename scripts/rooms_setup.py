def mcp_url(url: str) -> str:
    return url.rstrip("/") + "/mcp"


def hook_command(rooms_repo: Path, fmt: str, token_file: Path, url: str) -> str:
    script = shlex.quote(str(rooms_repo / "hooks" / "room_hook.py"))
    command = f"python3 {script} --format {fmt} --token-file {shlex.quote(str(token_file))}"
    if url != DEFAULT_URL:
        command += f" --url {shlex.quote(url)}"
    return command


def render_claude_mcp(url: str, token: str) -> dict[str, Any]:
    return {
        "mcpServers": {
            "rooms": {
                "type": "http",
                "url": mcp_url(url),
                "headers": {"Authorization": f"Bearer {token}"},
            }
        }
    }


def render_claude_settings(rooms_repo: Path, token_file: Path, url: str) -> dict[str, Any]:
    return {
        "permissions": {"allow": ["mcp__rooms__*"]},
        "hooks": {
            "Stop": [
                {
                    "hooks": [
                        {
                            "type": "command",
                            "command": hook_command(rooms_repo, "claude", token_file, url),
                            "timeout": HOOK_TIMEOUT,
                        }
                    ]
                }
            ]
        },
    }


def render_codex_hook_block(rooms_repo: Path, token_file: Path, url: str) -> str:
    command = json.dumps(hook_command(rooms_repo, "codex", token_file, url))
    return (
        "[[hooks.Stop]]\n"
        "[[hooks.Stop.hooks]]\n"
        'type = "command"\n'
        f"command = {command}\n"
        f"timeout = {HOOK_TIMEOUT}\n"
    )


def render_codex_profile(
    url: str,
    token: str,
    rooms_repo: Path,
    token_file: Path,
    profile_path: Path,
    *,
    trusted_hash: str | None = None,
) -> str:
    text = (
        "[mcp_servers.rooms]\n"
        f"url = {json.dumps(mcp_url(url))}\n"
        f"http_headers = {{ Authorization = {json.dumps('Bearer ' + token)} }}\n"
        'default_tools_approval_mode = "approve"\n'
        "tool_timeout_sec = 90\n"
        "startup_timeout_sec = 20\n"
        "\n" + render_codex_hook_block(rooms_repo, token_file, url)
    )
    if trusted_hash:
        text += "\n" + render_codex_trust_state(f"{profile_path}:stop:0:0", trusted_hash)
    return text


def render_codex_trust_state(key: str, trusted_hash: str) -> str:
    return f"[hooks.state.{json.dumps(key)}]\ntrusted_hash = {json.dumps(trusted_hash)}\n"


